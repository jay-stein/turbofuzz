const bytes = (text: string): ArrayBuffer => {
  const encoded = new TextEncoder().encode(text);
  return encoded.buffer.slice(encoded.byteOffset, encoded.byteOffset + encoded.byteLength) as ArrayBuffer;
};

test("a header-less pipe file keeps every record and names the columns", () => {
  const { dataset } = ingestDataset({ name: "cm.txt", delimiter: "auto", hasHeaders: true, buffer: bytes(FEC.join("\n") + "\n") });
  assert.equal(dataset.rowCount, FEC.length);
  assert.equal(dataset.columns.length, 15);
  assert.equal(dataset.columns[0]!.name, "Column 1");
  assert.equal(dataset.columns[0]!.raw[0], "C00000059");
});

test("full-width rows are never skipped as title rows", () => {
  const grid = FEC.map((line) => line.split("|"));
  const table = detectTable(grid);
  assert.equal(table.skipRows, 0);
  assert.equal(table.rows.length + table.headerRows, FEC.length);
});

test("rowLooksLikeData: ids and amounts under the same shapes, never a label row", () => {
  const grid = FEC.map((line) => line.split("|"));
  assert.equal(rowLooksLikeData(grid, 0), true);
  const withHeader = [["CMTE_ID", "CMTE_NM", "TRES_NM", "ST1", "ST2", "CITY", "ST", "ZIP", "DSGN", "TYPE", "PTY", "FREQ", "ORG", "CONN", "CAND"], ...grid];
  assert.equal(rowLooksLikeData(withHeader, 0), false);
  assert.equal(rowLooksLikeData([["Name", "City"], ["Ann", "Paris"], ["Bo", "Rome"], ["Cy", "Oslo"], ["Di", "Bern"]], 0), false);
});

test("look-alike: real title rows above a table are still skipped", () => {
  const grid = [
    ["Committee master, 2024"],
    ["Source: FEC", ""],
    ["id", "name", "city", "zip"],
    ["C1", "Alpha PAC", "Austin", "73301"],
    ["C2", "Beta PAC", "Boston", "02108"],
    ["C3", "Gamma PAC", "Chicago", "60601"],
  ];
  const table = detectTable(grid);
  assert.equal(table.skipRows, 2);
  assert.deepEqual(table.headers, ["id", "name", "city", "zip"]);
});

test("a quote that opens a field and closes with text after it does not swallow the rows below", () => {
  const rows = ['P1|"VAL" VALMA PAUL|REP', "P2|BORING, PAIJ|REP", "P3|PRAG, CHOMI|NNE", 'P4|"SMITH" JO|DEM', "P5|LEE, AN|DEM"];
  const parsed = parseDelimited(rows.join("\n") + "\n", { delimiter: "|", hasHeaders: false, normalizeRows: false });
  assert.equal(parsed.rows.length, 5);
  assert.equal(parsed.rows[4]![0], "P5");
});

test("look-alike: a properly quoted multi-line cell is still one cell", () => {
  const parsed = parseDelimited('a|b\n1|"line one\nline two"\n2|x\n', { delimiter: "|", hasHeaders: false, normalizeRows: false });
  assert.equal(parsed.rows.length, 3);
  assert.equal(parsed.rows[1]![1], "line one\nline two");
});
