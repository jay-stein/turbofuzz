/**
 * Vendors Natural Earth populated places (public domain) as a compact TypeScript
 * module for the Map page's city layer and city search: name, latitude and
 * longitude only, ordered by population (largest first), so "the biggest N" is a
 * prefix. Coordinates are kept to 0.01 degrees (about 1 km).
 *
 * Run: node tools/vendor-cities.mjs <ne_10m_populated_places_simple.geojson>
 */
import { readFileSync, writeFileSync } from "node:fs";

const input = process.argv[2];
if (input === undefined) {
  console.error("usage: node tools/vendor-cities.mjs <ne_10m_populated_places_simple.geojson>");
  process.exit(1);
}
const geo = JSON.parse(readFileSync(input, "utf8"));
const places = geo.features
  .map((f) => ({ name: String(f.properties.name ?? "").trim(), lat: f.properties.latitude, lon: f.properties.longitude, pop: f.properties.pop_max ?? 0 }))
  .filter((p) => p.name !== "" && Number.isFinite(p.lat) && Number.isFinite(p.lon) && !p.name.includes("|"))
  .sort((a, b) => b.pop - a.pop || a.name.localeCompare(b.name));
const names = places.map((p) => p.name).join("|");
// Hundredths of a degree, as one delta-free comma list: lat,lon,lat,lon...
const coords = places.map((p) => `${Math.round(p.lat * 100)},${Math.round(p.lon * 100)}`).join(",");
const out = `// Generated by tools/vendor-cities.mjs from Natural Earth ne_10m_populated_places_simple
// (public domain). ${places.length} places, largest population first. Do not edit by hand.
export const CITY_NAMES = ${JSON.stringify(names)};
/** Latitude, longitude pairs in hundredths of a degree, in CITY_NAMES order. */
export const CITY_COORDS = ${JSON.stringify(coords)};
`;
writeFileSync(new URL("../src/data/reference/world-cities.ts", import.meta.url), out);
console.log(`wrote src/data/reference/world-cities.ts: ${places.length} places, ${out.length} bytes`);
