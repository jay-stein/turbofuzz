/**
 * Vendors a Natural Earth basemap (world-atlas@2, public domain) as a
 * TypeScript module so the map card can lazily import it with no network and
 * no JSON-import plugin.
 *
 * Run: node tools/vendor-world.mjs <countries-110m.json>
 *      node tools/vendor-world.mjs <countries-50m.json> --out world-50m
 */
import { readFileSync, writeFileSync } from "node:fs";
import { basename } from "node:path";

const args = process.argv.slice(2);
const input = args[0];
const outIndex = args.indexOf("--out");
const moduleName = outIndex >= 0 ? args[outIndex + 1] : "world-110m";
if (input === undefined || moduleName === undefined) {
  console.error(
    "usage: node tools/vendor-world.mjs <countries-110m.json> [--out world-110m]",
  );
  process.exit(1);
}

const world = JSON.parse(readFileSync(input, "utf8"));
if (world.type !== "Topology" || world.objects.countries === undefined) {
  console.error("not a TopoJSON world-atlas file");
  process.exit(1);
}

const suffix = moduleName.replace(/^world-/, "").toUpperCase();
const exportName = `WORLD_${suffix.replace(/[^A-Z0-9]/g, "_")}`;
const out = `// Generated by tools/vendor-world.mjs from world-atlas@2 ${basename(input)}
// (Natural Earth 4.1.0, public domain). Do not edit by hand.
import type { TopoWorld } from "./topo.js";

export const ${exportName} = ${JSON.stringify(world)} as unknown as TopoWorld;
`;

writeFileSync(new URL(`../src/data/${moduleName}.ts`, import.meta.url), out);
console.log(`wrote src/data/${moduleName}.ts (${out.length} bytes)`);
