/**
 * Vendors the Natural Earth 110m basemap (world-atlas@2, public domain) as a
 * TypeScript module so the map card can lazily import it with no network and
 * no JSON-import plugin. Run: node tools/vendor-world.mjs <input.json>
 */
import { readFileSync, writeFileSync } from "node:fs";

const input = process.argv[2];
if (input === undefined) {
  console.error("usage: node tools/vendor-world.mjs <countries-110m.json>");
  process.exit(1);
}

const world = JSON.parse(readFileSync(input, "utf8"));
if (world.type !== "Topology" || world.objects.countries === undefined) {
  console.error("not a TopoJSON world-atlas file");
  process.exit(1);
}

const out = `// Generated by tools/vendor-world.mjs from world-atlas@2 countries-110m.json
// (Natural Earth 4.1.0, public domain). Do not edit by hand.
import type { TopoWorld } from "./topo.js";

export const WORLD_110M = ${JSON.stringify(world)} as unknown as TopoWorld;
`;

writeFileSync(new URL("../src/data/world-110m.ts", import.meta.url), out);
console.log(`wrote src/data/world-110m.ts (${out.length} bytes)`);
